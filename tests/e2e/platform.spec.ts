import { test, expect, request, type APIRequestContext } from '@playwright/test';
import dotenv from 'dotenv';
dotenv.config({ quiet: true });

const password = process.env.DEMO_PASSWORD || 'Acolhe+2026!';
async function login(email: string, pass = password): Promise<APIRequestContext> {
  const ctx = await request.newContext({ baseURL: 'http://localhost:3000', extraHTTPHeaders: { Origin: 'http://localhost:3000' } });
  const response = await ctx.post('/api/login', { data: { email, password: pass } });
  expect(response.status(), await response.text()).toBe(200);
  return ctx;
}

test('API: isolamento, snapshots, concorrência e devolutiva persistente', async () => {
  const anonymous = await request.newContext({ baseURL: 'http://localhost:3000' });
  expect((await anonymous.get('/api/simulations')).status()).toBe(401);
  const instructor = await login('instrutor@acolhe.local');
  const learner = await login('aluno@acolhe.local');
  const casesResponse = await learner.get('/api/cases');
  expect(casesResponse.ok()).toBeTruthy();
  const cases = (await casesResponse.json()).cases;
  expect(cases.length).toBeGreaterThanOrEqual(3);
  expect(JSON.stringify(cases)).not.toMatch(/acceptedRisks|requiredTopics|acceptedCiap|rationale/);
  const started = await learner.post('/api/simulations', { data: { caseId: cases[0].id } });
  expect(started.ok(), await started.text()).toBeTruthy();
  const simulation = (await started.json()).simulation;
  const restarted = await learner.post('/api/simulations', { data: { caseId: cases[0].id } });
  expect((await restarted.json()).simulation.id).toBe(simulation.id);
  const suffix = Date.now();
  const cls = await instructor.post('/api/instructor/classes', { data: { name: `Teste isolamento ${suffix}` } });
  expect(cls.ok(), await cls.text()).toBeTruthy();
  const classId = (await cls.json()).id;
  const email = `teste-${suffix}@acolhe.local`;
  const created = await instructor.post('/api/instructor/students', { data: { name: 'Aluno de teste', email, password, classId } });
  expect(created.ok(), await created.text()).toBeTruthy();
  const other = await login(email);
  expect([403, 404]).toContain((await other.get(`/api/simulations/${simulation.id}`)).status());
  expect((await other.get('/api/instructor')).status()).toBe(403);
  const wrongOrigin = await learner.put(`/api/simulations/${simulation.id}`, { headers: { Origin: 'https://outro.example' }, data: {} });
  expect(wrongOrigin.status()).toBe(403);
  const catalogs = (await (await learner.get('/api/catalogs')).json());
  const draft = { ...simulation.draft, ciap: catalogs.ciap[0].code, text: 'Paciente relata dor de cabeça. Foram registradas as informações disponíveis na ficha.', document: null, risk: 'NON_ACUTE', outcome: 'RELEASE' };
  const saved = await learner.put(`/api/simulations/${simulation.id}`, { data: { draft, revision: simulation.revision } });
  expect(saved.ok(), await saved.text()).toBeTruthy();
  const revision = (await saved.json()).revision;
  expect((await learner.put(`/api/simulations/${simulation.id}`, { data: { draft, revision: simulation.revision } })).status()).toBe(409);
  const key = `e2e-${suffix}`;
  const submission = await learner.post(`/api/simulations/${simulation.id}/submit`, { data: { revision, idempotencyKey: key } });
  expect(submission.ok(), await submission.text()).toBeTruthy();
  const attempt = (await submission.json()).attempt;
  const duplicate = await learner.post(`/api/simulations/${simulation.id}/submit`, { data: { revision, idempotencyKey: key } });
  expect((await duplicate.json()).attempt.id).toBe(attempt.id);
  await expect.poll(async () => {
    const response = await learner.get(`/api/simulations/${simulation.id}`);
    return (await response.json()).simulation.attempts.find((a: {id: string}) => a.id === attempt.id).status;
  }, { timeout: 30000 }).toBe('COMPLETED');
  const completed = (await (await learner.get(`/api/simulations/${simulation.id}`)).json()).simulation;
  const completedAttempt = completed.attempts.find((a: {id: string}) => a.id === attempt.id);
  expect(completedAttempt.feedback.clinicalPending).toBe(true);
  expect(completedAttempt.feedback.mode).toBe('demo');
  expect(completedAttempt.feedback.items.every((i: {category: string}) => !['RISK', 'CIAP', 'OUTCOME', 'PROCEDURE'].includes(i.category))).toBe(true);
  const edited = await learner.put(`/api/simulations/${simulation.id}`, { data: { revision, draft: { ...draft, text: 'Registro revisado pelo aluno.' } } });
  expect(edited.ok(), await edited.text()).toBeTruthy();
  const after = (await (await learner.get(`/api/simulations/${simulation.id}`)).json()).simulation;
  expect(after.attempts.find((a: {id: string}) => a.id === attempt.id).snapshot.text).toBe(draft.text);
  const review = await instructor.post(`/api/attempts/${attempt.id}/reviews`, { data: { comment: 'Revisão de teste: confira a organização do relato.' } });
  expect(review.ok(), await review.text()).toBeTruthy();
  expect([403, 404]).toContain((await other.post(`/api/attempts/${attempt.id}/reviews`, { data: { comment: 'não permitido' } })).status());
  await Promise.all([anonymous.dispose(), instructor.dispose(), learner.dispose(), other.dispose()]);
});

test('Interface: login, adicionar cidadão, preencher e retomar', async ({ page }) => {
  await page.goto('/login');
  await page.getByLabel('E-mail', { exact: true }).fill('aluno@acolhe.local');
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Lista de atendimentos' })).toBeVisible();
  await page.getByRole('button', { name: 'Adicionar cidadão' }).click();
  await expect(page.getByText('Gestante', { exact: false }).first()).toBeVisible();
  await page.locator('.case-option').first().getByRole('button', { name: 'Iniciar escuta' }).click();
  await expect(page.getByRole('heading', { name: 'Escuta inicial', exact: true })).toBeVisible();
  const record = page.getByRole('textbox', { name: 'Descrição da escuta inicial', exact: true });
  const text = 'Paciente relata dor de cabeça. Dados da ficha consultados durante a escuta.';
  await record.fill(text);
  await page.getByRole('combobox', { name: 'Motivo da consulta · CIAP-2 *' }).fill('W78');
  await page.getByRole('option', { name: /W78/ }).click();
  await page.getByRole('radio', { name: 'Não aguda', exact: true }).check();
  await page.getByRole('radio', { name: 'Liberar cidadão', exact: true }).check();
  await page.getByRole('button', { name: 'Conversa', exact: true }).click();
  await page.getByLabel('Pergunta ao paciente').fill('Você tem alergias?');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await expect(page.locator('.message.assistant').last()).toBeVisible();
  await expect(page.locator('.save-state')).toContainText('Salvo');
  await page.reload();
  await expect(record).toHaveText(text);
  await expect(page.getByRole('radio', { name: 'Liberar cidadão', exact: true })).toBeChecked();
  const submit = page.getByRole('button', { name: /Concluir simulação|Enviar nova tentativa|Finalizar escuta inicial/ });
  await submit.click();
  await expect(page.getByText('Análise formativa disponível', { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.locator('.inline-highlight').filter({ hasText: 'dor de cabeça' }).first()).toBeVisible();
  await page.locator('.inline-highlight').filter({ hasText: 'dor de cabeça' }).first().click();
  await page.getByRole('button', { name: 'Aplicar sugestão ao rascunho' }).first().click();
  await expect(record).toContainText('cefaleia');
  await expect(page.locator('.snapshot')).toContainText('dor de cabeça');
  await expect(page.locator('.save-state')).toContainText('Salvo');
  await page.getByRole('button', { name: 'Enviar nova tentativa' }).click();
  await expect(page.getByText('Análise formativa disponível', { exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: 'Ficha do cidadão', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.screenshot({ path: 'test-results/acolhimento-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/acolhimento-mobile.png', fullPage: true });
});
